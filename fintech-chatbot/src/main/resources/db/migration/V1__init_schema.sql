-- =====================================================================
-- V1: Schema ban đầu cho 18 thực thể E-01 → E-18 (USE_CASES.md §5)
-- Viết theo SQL chuẩn để chạy được trên cả PostgreSQL và H2 (test).
-- Cột văn bản dài dùng VARCHAR không giới hạn độ dài (PostgreSQL: tương đương TEXT).
-- Mọi dữ liệu của user có user_id ON DELETE CASCADE để UC-D03 xóa tài khoản xóa sạch dữ liệu.
-- =====================================================================

-- E-01
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(255) NOT NULL UNIQUE,
    password_hash       VARCHAR(255) NOT NULL,
    full_name           VARCHAR(100) NOT NULL,
    role                VARCHAR(20)  NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    token_version       INTEGER      NOT NULL DEFAULT 0,
    failed_login_count  INTEGER      NOT NULL DEFAULT 0,
    login_locked_until  TIMESTAMP,
    last_login_at       TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- E-02
CREATE TABLE wallets (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name             VARCHAR(100)  NOT NULL,
    type             VARCHAR(20)   NOT NULL,
    initial_balance  NUMERIC(18, 0) NOT NULL DEFAULT 0,
    current_balance  NUMERIC(18, 0) NOT NULL DEFAULT 0,
    is_default       BOOLEAN       NOT NULL DEFAULT FALSE,
    is_archived      BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wallets_user_name UNIQUE (user_id, name)
);

-- E-03 (user_id NULL = danh mục mặc định)
CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       REFERENCES users (id) ON DELETE CASCADE,
    name        VARCHAR(100) NOT NULL,
    type        VARCHAR(20)  NOT NULL,
    icon        VARCHAR(50),
    parent_id   BIGINT       REFERENCES categories (id),
    is_hidden   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_categories_user ON categories (user_id);

-- E-06
CREATE TABLE saving_goals (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name            VARCHAR(100)   NOT NULL,
    target_amount   NUMERIC(18, 0) NOT NULL,
    current_amount  NUMERIC(18, 0) NOT NULL DEFAULT 0,
    deadline        DATE,
    status          VARCHAR(20)    NOT NULL,
    created_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_saving_goals_user ON saving_goals (user_id);

-- E-07
CREATE TABLE debts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type          VARCHAR(20)    NOT NULL,
    counterparty  VARCHAR(100)   NOT NULL,
    principal     NUMERIC(18, 0) NOT NULL,
    remaining     NUMERIC(18, 0) NOT NULL,
    start_date    DATE           NOT NULL,
    due_date      DATE,
    note          VARCHAR(500),
    status        VARCHAR(20)    NOT NULL,
    created_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_debts_user ON debts (user_id);

-- E-04
CREATE TABLE transactions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    wallet_id     BIGINT         NOT NULL REFERENCES wallets (id),
    to_wallet_id  BIGINT         REFERENCES wallets (id),
    category_id   BIGINT         REFERENCES categories (id),
    type          VARCHAR(20)    NOT NULL,
    amount        NUMERIC(18, 0) NOT NULL,
    txn_date      DATE           NOT NULL,
    note          VARCHAR(500),
    source        VARCHAR(20)    NOT NULL,
    debt_id       BIGINT         REFERENCES debts (id),
    goal_id       BIGINT         REFERENCES saving_goals (id),
    created_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_transactions_amount_positive CHECK (amount > 0)
);
CREATE INDEX idx_transactions_user_date ON transactions (user_id, txn_date);
CREATE INDEX idx_transactions_wallet ON transactions (wallet_id);
CREATE INDEX idx_transactions_category ON transactions (category_id);

-- E-05
CREATE TABLE budgets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id     BIGINT         NOT NULL REFERENCES categories (id),
    budget_month    VARCHAR(7)     NOT NULL,
    limit_amount    NUMERIC(18, 0) NOT NULL,
    warn_threshold  INTEGER        NOT NULL DEFAULT 80,
    created_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_budgets_user_category_month UNIQUE (user_id, category_id, budget_month)
);

-- E-08
CREATE TABLE recurring_rules (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    wallet_id      BIGINT         NOT NULL REFERENCES wallets (id),
    category_id    BIGINT         REFERENCES categories (id),
    type           VARCHAR(20)    NOT NULL,
    amount         NUMERIC(18, 0) NOT NULL,
    note           VARCHAR(500),
    frequency      VARCHAR(20)    NOT NULL,
    start_date     DATE           NOT NULL,
    next_run_date  DATE           NOT NULL,
    auto_create    BOOLEAN        NOT NULL DEFAULT FALSE,
    is_active      BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_recurring_rules_next_run ON recurring_rules (is_active, next_run_date);

-- E-09
CREATE TABLE financial_profiles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT         NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    monthly_income  NUMERIC(18, 0),
    dependents      INTEGER        NOT NULL DEFAULT 0,
    goals           VARCHAR(500),
    risk_score      INTEGER,
    risk_level      VARCHAR(10),
    created_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- E-10
CREATE TABLE conversations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title       VARCHAR(200) NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_conversations_user ON conversations (user_id, updated_at);

-- E-11
CREATE TABLE messages (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  BIGINT      NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    role             VARCHAR(20) NOT NULL,
    content          VARCHAR     NOT NULL,
    input_mode       VARCHAR(10) NOT NULL,
    intent           VARCHAR(40),
    citations        VARCHAR,
    created_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_messages_conversation ON messages (conversation_id, created_at);

-- E-12
CREATE TABLE documents (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(300)  NOT NULL,
    source_id     VARCHAR(20)   NOT NULL,
    url           VARCHAR(1000),
    license       VARCHAR(200)  NOT NULL,
    language      VARCHAR(10)   NOT NULL,
    accessed_at   DATE,
    status        VARCHAR(20)   NOT NULL,
    content_hash  VARCHAR(64),
    uploaded_by   BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_documents_status ON documents (status);

-- E-13
CREATE TABLE chunks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT       NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    chunk_index  INTEGER      NOT NULL,
    content      VARCHAR      NOT NULL,
    heading      VARCHAR(300),
    page_number  INTEGER,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_chunks_document ON chunks (document_id, chunk_index);

-- E-14
CREATE TABLE feedbacks (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    message_id     BIGINT        NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    rating         VARCHAR(10)   NOT NULL,
    reason         VARCHAR(30),
    comment        VARCHAR(1000),
    review_status  VARCHAR(20),
    admin_note     VARCHAR(1000),
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_feedbacks_message_user UNIQUE (message_id, user_id)
);
CREATE INDEX idx_feedbacks_review_status ON feedbacks (review_status);

-- E-15
CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type        VARCHAR(30)  NOT NULL,
    content     VARCHAR(500) NOT NULL,
    ref_id      BIGINT,
    is_read     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_notifications_user ON notifications (user_id, is_read);

-- E-16
CREATE TABLE ai_config (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key    VARCHAR(100) NOT NULL UNIQUE,
    config_value  VARCHAR      NOT NULL,
    updated_by    BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- E-17
CREATE TABLE ai_data_permissions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT    NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    allow_transactions  BOOLEAN   NOT NULL DEFAULT TRUE,
    allow_budgets       BOOLEAN   NOT NULL DEFAULT TRUE,
    allow_debts         BOOLEAN   NOT NULL DEFAULT TRUE,
    allow_goals         BOOLEAN   NOT NULL DEFAULT TRUE,
    allow_profile       BOOLEAN   NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- E-18
CREATE TABLE market_rates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(20)    NOT NULL,
    symbol      VARCHAR(30)    NOT NULL,
    buy         NUMERIC(18, 4),
    sell        NUMERIC(18, 4),
    source_id   VARCHAR(20)    NOT NULL,
    fetched_at  TIMESTAMP      NOT NULL,
    created_at  TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_market_rates_lookup ON market_rates (kind, symbol, fetched_at);
