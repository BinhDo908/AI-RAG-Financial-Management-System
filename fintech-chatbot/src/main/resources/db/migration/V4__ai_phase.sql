-- UC-C04 AF-2: lịch sử thay đổi cấu hình AI
CREATE TABLE ai_config_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key   VARCHAR(100) NOT NULL,
    old_value    VARCHAR,
    new_value    VARCHAR      NOT NULL,
    changed_by   BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ai_config_history_key ON ai_config_history (config_key, created_at);

-- UC-C03 AF-1: kết quả các lần chạy bộ đánh giá chatbot
CREATE TABLE eval_runs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_name    VARCHAR(200)     NOT NULL,
    total_questions INTEGER          NOT NULL,
    hit_rate        DOUBLE PRECISION NOT NULL,
    citation_rate   DOUBLE PRECISION NOT NULL,
    accuracy        DOUBLE PRECISION NOT NULL,
    config_snapshot VARCHAR          NOT NULL,
    details         VARCHAR          NOT NULL,
    run_by          BIGINT           REFERENCES users (id) ON DELETE SET NULL,
    created_at      TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP
);

